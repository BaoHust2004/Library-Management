CREATE DATABASE qltv;
\c qltv


-- Tạo bảng Nhân viên
CREATE TABLE nhanvien (
    idnhanvien SERIAL PRIMARY KEY,
    ten VARCHAR(100),
    chucvu VARCHAR(50),
    sodienthoai VARCHAR(15),
    taikhoan VARCHAR(50),
    matkhau VARCHAR(50)
);

-- Tạo bảng Độc giả
CREATE TABLE docgia (
    iddocgia SERIAL PRIMARY KEY,
    sodienthoai VARCHAR(15),
    ten VARCHAR(100),
    diachi VARCHAR(255),
    tuoi INT,
    taikhoan VARCHAR(50),
    matkhau VARCHAR(50),
    soluotmuon INT
);

-- Tạo bảng Báo cáo tháng
CREATE TABLE baocaothang (
    thoigian VARCHAR(15) PRIMARY KEY,
    thu INT,
    chi INT,
    soluongsachchuatra INT,
    idnhanvien INT
);

-- Tạo bảng Sách
CREATE TABLE sach (
    idsach SERIAL PRIMARY KEY,
    phanloai VARCHAR(50),
    phimuon INT,
    ten VARCHAR(100),
    trangthai varchar(20),
    nhaxuatban VARCHAR(100),
    tacgia VARCHAR(100),
    luotmuon INT,
    idnhanvien INT
);

-- Tạo bảng Phiếu mượn
CREATE TABLE phieumuon (
    idphieumuon SERIAL PRIMARY KEY,
    ngaymuon DATE,
    ngaydenhan DATE,
    idsach INT,
    iddocgia INT
);

-- thêm khóa ngoại cho bảng báo cáo tháng
alter table baocaothang
add constraint fk_nhanvien_baocao
foreign key (idnhanvien) references nhanvien(idnhanvien);

-- thêm khóa ngoại cho bảng sách
alter table sach
add constraint fk_nhanvien_sach
foreign key (idnhanvien) references nhanvien(idnhanvien);

-- thêm khóa ngoại cho bảng phiếu mượn
alter table phieumuon
add constraint fk_docgia_phieumuon
foreign key (iddocgia) references docgia(iddocgia);

alter table phieumuon
add constraint fk_sach_phieumuon
foreign key (idsach) references sach(idsach);


